import { chromium } from '@playwright/test';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 1, hasTouch: true });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto('http://localhost:5173/?fps');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/01-splash.png' });
await page.mouse.click(400, 200);
await page.waitForTimeout(800);
await page.screenshot({ path: 'shots/02-menu.png' });
await page.click('[data-action=quick]');
await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/03-setup.png' });
await page.click('[data-action=start]');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/04-coin.png' });
await page.click('[data-action=heads]');
await page.waitForTimeout(300);
await page.click('[data-action=receive]');
await page.waitForTimeout(2500);
await page.screenshot({ path: 'shots/05-kickoff.png' });
await page.waitForTimeout(8000);
await page.screenshot({ path: 'shots/06-after-kick.png' });
console.log(errors.join('\n') || 'no errors');
await browser.close();
